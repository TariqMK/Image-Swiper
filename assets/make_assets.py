"""Builds every Image Swiper brand image from the icon master SVGs.

Writes:
  assets/icon/image-swiper.png       1024 x 1024 px
  assets/icon/image-swiper.ico       16-256 px, for the Windows exe
  assets/icon/image-swiper.icns      16-1024 px with Retina sizes, for the macOS app
  assets/banner.png                  README banner, 1280 x 320 px drawn at 2x
  assets/social-card.png             GitHub social preview, 1280 x 640 px
  image_swiper/app_icon.py           window and toolbar icons embedded as PNG data

Reads assets/icon/image-swiper.svg (master) and assets/icon/image-swiper-small.svg (16-32 px).
Colours come from image_swiper/theme.py, so the brand follows the app.

Run from the repository root, in any Python 3.10+ environment:
  pip install PySide6-Essentials Pillow
  python assets/make_assets.py
Add --guides <file.png> to also write a social card with its 80 px safe area drawn on.
"""

import argparse
import base64
import io
import sys
from pathlib import Path

from PIL import Image, ImageChops
from PySide6.QtCore import QByteArray, QBuffer, QIODevice, QPointF, QRectF
from PySide6.QtGui import (QColor, QFont, QFontDatabase, QFontMetrics, QGuiApplication, QImage,
                           QPainter, QPainterPath, QPen)
from PySide6.QtSvg import QSvgRenderer

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from image_swiper.theme import Theme  # noqa: E402  (colour tokens only; no window needed)

# ---- Values to change -------------------------------------------------------------------
NAME = 'Image Swiper'
TAGLINE = 'Keep or delete. One at a time.'
SUBLINE = 'Windows · macOS · Linux'
# ------------------------------------------------------------------------------------------

ASSETS = ROOT / 'assets'
MASTER = ASSETS / 'icon' / 'image-swiper.svg'
SMALL = ASSETS / 'icon' / 'image-swiper-small.svg'
SMALL_MAX = 32  # Sizes up to this use the simplified SVG.

SANS = ['Segoe UI Variable Display', 'Segoe UI', 'SF Pro Display', 'Helvetica Neue', 'Inter',
        'Cantarell', 'Noto Sans']
MONO = ['Cascadia Mono', 'SF Mono', 'Menlo', 'JetBrains Mono', 'Consolas', 'DejaVu Sans Mono']


# ---- Icon -------------------------------------------------------------------------------

def render_svg(path: Path, size: int, canvas: int | None = None) -> Image.Image:
    """Render an SVG to a square RGBA image, optionally centred on a larger transparent canvas."""
    canvas = canvas or size
    renderer = QSvgRenderer(QByteArray(path.read_bytes()))
    if not renderer.isValid():
        sys.exit(f'Cannot read {path}')
    image = QImage(canvas, canvas, QImage.Format.Format_ARGB32)
    image.fill(0)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    offset = (canvas - size) / 2
    renderer.render(painter, QRectF(offset, offset, size, size))
    painter.end()
    return to_pil(image)


def to_pil(image: QImage) -> Image.Image:
    buffer = QBuffer()
    buffer.open(QIODevice.OpenModeFlag.WriteOnly)
    image.save(buffer, 'PNG')
    return Image.open(io.BytesIO(bytes(buffer.data()))).convert('RGBA')


def icon(size: int) -> Image.Image:
    return render_svg(SMALL if size <= SMALL_MAX else MASTER, size)


def mac_icon(size: int) -> Image.Image:
    """macOS icons sit on an 824 px tile inside 1024 px, so they match the Dock's other icons."""
    return render_svg(SMALL if size <= SMALL_MAX else MASTER, round(size * 824 / 1024), size)


def png_bytes(image: Image.Image) -> bytes:
    out = io.BytesIO()
    image.save(out, 'PNG', optimize=True)
    return out.getvalue()


def write_icons() -> Image.Image:
    folder = ASSETS / 'icon'
    master = icon(1024)
    master.save(folder / 'image-swiper.png', optimize=True)

    ico_sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    ico_images = [icon(s) for s in ico_sizes]
    ico_images[-1].save(folder / 'image-swiper.ico', format='ICO',
                        sizes=[(s, s) for s in ico_sizes], append_images=ico_images[:-1])

    icns_sizes = [16, 32, 64, 128, 256, 512, 1024]
    icns_images = [mac_icon(s) for s in icns_sizes]
    icns_images[-1].save(folder / 'image-swiper.icns', format='ICNS',
                         append_images=icns_images[:-1])

    # Embedded in the package, so the app ships no loose icon file.
    window = {s: base64.b64encode(png_bytes(icon(s))).decode() for s in (16, 32, 48, 256)}
    toolbar = base64.b64encode(png_bytes(render_svg(SMALL, 64))).decode()
    lines = ['"""App icon as PNG data. Generated by assets/make_assets.py; do not edit."""', '',
             '# Window and taskbar icon, largest first, for Tk iconphoto.',
             'WINDOW = [']
    lines += [f"    '{window[s]}',  # {s} px" for s in (256, 48, 32, 16)]
    lines += [']', '', '# Toolbar mark, drawn from the simplified icon (64 px).',
              f"TOOLBAR = '{toolbar}'", '']
    (ROOT / 'image_swiper' / 'app_icon.py').write_text('\n'.join(lines), encoding='utf-8')
    return master


# ---- Text helpers ----------------------------------------------------------------------

def font(families: list[str], pixel_size: int, weight: QFont.Weight) -> QFont:
    available = set(QFontDatabase.families())
    result = QFont()
    result.setFamilies([f for f in families if f in available] or families)
    result.setPixelSize(pixel_size)
    result.setWeight(weight)
    # Variable fonts such as Segoe UI Variable need the weight axis set as well.
    if hasattr(result, 'setVariableAxis'):
        result.setVariableAxis(QFont.Tag('wght'), float(weight.value))
    return result


def fit(base: QFont, text: str, max_width: float) -> QFont:
    """Shrink the font 2 px at a time until the text fits max_width."""
    result = QFont(base)
    while QFontMetrics(result).horizontalAdvance(text) > max_width - 8 and result.pixelSize() > 12:
        result.setPixelSize(result.pixelSize() - 2)
    if result.pixelSize() < base.pixelSize():
        print(f'Warning: "{text}" shrank from {base.pixelSize()} to {result.pixelSize()} px.')
    return result


def draw_svg(painter: QPainter, path: Path, rect: QRectF) -> None:
    QSvgRenderer(QByteArray(path.read_bytes())).render(painter, rect)


# ---- Banner: 1280 x 320, drawn at 2x ---------------------------------------------------

def write_banner() -> None:
    k = 2
    width, height = 1280 * k, 320 * k
    image = QImage(width, height, QImage.Format.Format_ARGB32)
    image.fill(0)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.TextAntialiasing)

    outline = QPainterPath()
    outline.addRoundedRect(QRectF(k / 2, k / 2, width - k, height - k), 24 * k, 24 * k)
    painter.fillPath(outline, QColor(Theme.window))
    painter.setPen(QPen(QColor(Theme.hairline), k))
    painter.drawPath(outline)

    icon_size, gap = 176 * k, 48 * k
    name_font = font(SANS, 96 * k, QFont.Weight.DemiBold)
    tag_font = font(MONO, 24 * k, QFont.Weight.Normal)
    name_m, tag_m = QFontMetrics(name_font), QFontMetrics(tag_font)
    text_width = max(name_m.horizontalAdvance(NAME), tag_m.horizontalAdvance(TAGLINE))
    left = (width - (icon_size + gap + text_width)) / 2
    draw_svg(painter, MASTER, QRectF(left, (height - icon_size) / 2, icon_size, icon_size))

    # Name cap height plus a 44 px gap (clears the descenders) plus tagline cap height,
    # centred as one block.
    line_gap = 44 * k
    block = name_m.capHeight() + line_gap + tag_m.capHeight()
    name_base = (height - block) / 2 + name_m.capHeight()
    text_left = left + icon_size + gap
    painter.setFont(name_font)
    painter.setPen(QColor(Theme.text))
    painter.drawText(QPointF(text_left, name_base), NAME)
    painter.setFont(tag_font)
    painter.setPen(QColor(Theme.text_secondary))
    painter.drawText(QPointF(text_left + 4 * k, name_base + line_gap + tag_m.capHeight()), TAGLINE)
    painter.end()
    image.save(str(ASSETS / 'banner.png'))


# ---- Social card: 1280 x 640, GitHub repo card layout ----------------------------------

CARD_W, CARD_H, SAFE = 1280, 640, 80
CARD_ICON, CARD_ICON_TOP, CARD_ICON_GAP = 168, 150, 40
CARD_NAME_PX, CARD_TAGLINE_PX, CARD_TAGLINE_BASE = 112, 34, 420
CARD_SUBLINE_PX, CARD_SUBLINE_BASE = 24, 476


def write_social_card(guides: str | None) -> bool:
    image = QImage(CARD_W, CARD_H, QImage.Format.Format_ARGB32)
    image.fill(QColor(Theme.window))
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.TextAntialiasing)
    safe_width = CARD_W - 2 * SAFE

    name_font = fit(font(SANS, CARD_NAME_PX, QFont.Weight.DemiBold), NAME,
                    safe_width - CARD_ICON - CARD_ICON_GAP)
    name_width = QFontMetrics(name_font).horizontalAdvance(NAME)
    left = (CARD_W - (CARD_ICON + CARD_ICON_GAP + name_width)) / 2
    draw_svg(painter, MASTER, QRectF(left, CARD_ICON_TOP, CARD_ICON, CARD_ICON))
    baseline = CARD_ICON_TOP + CARD_ICON / 2 + QFontMetrics(name_font).capHeight() / 2
    painter.setFont(name_font)
    painter.setPen(QColor(Theme.text))
    painter.drawText(QPointF(left + CARD_ICON + CARD_ICON_GAP - name_font.pixelSize() * 0.035,
                             baseline), NAME)

    for text, px, colour, y in ((TAGLINE, CARD_TAGLINE_PX, Theme.text_secondary, CARD_TAGLINE_BASE),
                                (SUBLINE, CARD_SUBLINE_PX, Theme.text_muted, CARD_SUBLINE_BASE)):
        if not text:
            continue
        text_font = fit(font(MONO, px, QFont.Weight.Normal), text, safe_width)
        painter.setFont(text_font)
        painter.setPen(QColor(colour))
        painter.drawText(QPointF((CARD_W - QFontMetrics(text_font).horizontalAdvance(text)) / 2, y),
                         text)
    painter.end()
    image.save(str(ASSETS / 'social-card.png'))

    if guides:
        copy = image.copy()
        painter = QPainter(copy)
        painter.setPen(QPen(QColor('#d1242f'), 2))
        painter.drawRect(SAFE, SAFE, CARD_W - 2 * SAFE, CARD_H - 2 * SAFE)
        painter.end()
        copy.save(guides)

    # Safe area check: nothing but background within 80 px of each edge.
    card = to_pil(image).convert('RGB')
    bounds = ImageChops.difference(card, Image.new('RGB', card.size, Theme.window)).getbbox()
    ok = bool(bounds) and bounds[0] >= SAFE and bounds[1] >= SAFE \
        and bounds[2] <= CARD_W - SAFE and bounds[3] <= CARD_H - SAFE
    print(f'Social card content box {bounds}: safe area {"OK" if ok else "VIOLATED"}')
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--guides', help='Also write the social card with its safe area drawn on.')
    args = parser.parse_args()
    app = QGuiApplication(sys.argv[:1])  # noqa: F841  Qt needs an application object for fonts.
    write_icons()
    write_banner()
    ok = write_social_card(args.guides)
    print('Wrote icon files, image_swiper/app_icon.py, banner.png and social-card.png')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
